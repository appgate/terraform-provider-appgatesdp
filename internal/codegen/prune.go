package codegen

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

// pruneFrameworkOutput reduces tfplugingen-framework output to the schema
// functions.
//
// tfplugingen-framework v0.4.1 always emits model structs and custom
// type/value implementations for every nested attribute, named after the
// attribute alone. SDP schemas reuse nested attribute names at different
// depths (e.g. appliance gateway and portal both have allow_sources), so the
// generated packages declare the same type twice and do not compile. The
// provider reads and writes state through tftypes and never uses the models,
// so they are removed together with the CustomType references to them; the
// schema itself (attributes, validators, defaults, plan modifiers) is kept
// exactly as generated.
func pruneFrameworkOutput(dir string) error {
	return filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(path, ".go") {
			return err
		}
		src, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		out, err := pruneFile(src)
		if err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		return os.WriteFile(path, out, 0o644)
	})
}

func pruneFile(src []byte) ([]byte, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "", src, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	var decls []ast.Decl
	for _, d := range f.Decls {
		if fn, ok := d.(*ast.FuncDecl); ok && fn.Recv == nil && strings.HasSuffix(fn.Name.Name, "Schema") {
			ast.Inspect(fn, func(n ast.Node) bool {
				if cl, ok := n.(*ast.CompositeLit); ok {
					cl.Elts = removeCustomType(cl.Elts)
				}
				return true
			})
			decls = append(decls, fn)
		}
	}
	if len(decls) == 0 {
		return nil, fmt.Errorf("no schema function found")
	}
	used := map[string]bool{}
	for _, d := range decls {
		ast.Inspect(d, func(n ast.Node) bool {
			if sel, ok := n.(*ast.SelectorExpr); ok {
				if id, ok := sel.X.(*ast.Ident); ok {
					used[id.Name] = true
				}
			}
			return true
		})
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by terraform-plugin-framework-generator DO NOT EDIT.\n// Pruned to the schema function by sdpgen (see internal/codegen/prune.go).\n\npackage %s\n\nimport (\n", f.Name.Name)
	for _, imp := range f.Imports {
		p, _ := strconv.Unquote(imp.Path.Value)
		name := p[strings.LastIndex(p, "/")+1:]
		if imp.Name != nil {
			name = imp.Name.Name
		}
		if used[name] {
			fmt.Fprintf(&b, "%s\n", imp.Path.Value)
		}
	}
	b.WriteString(")\n\n")
	for _, d := range decls {
		if err := format.Node(&b, fset, d); err != nil {
			return nil, err
		}
		b.WriteString("\n\n")
	}
	return format.Source(b.Bytes())
}

func removeCustomType(elts []ast.Expr) []ast.Expr {
	out := elts[:0]
	for _, e := range elts {
		if kv, ok := e.(*ast.KeyValueExpr); ok {
			if id, ok := kv.Key.(*ast.Ident); ok && id.Name == "CustomType" {
				continue
			}
		}
		out = append(out, e)
	}
	return out
}
