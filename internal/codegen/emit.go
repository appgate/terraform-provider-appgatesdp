const generatedHeader = "Code generated by sdpgen. DO NOT EDIT."

// pascal converts snake_case to the PascalCase tfplugingen-framework uses for
// package level identifiers.
func pascal(s string) string {
	parts := strings.Split(s, "_")
	for i, p := range parts {
		if p != "" {
			parts[i] = strings.ToUpper(p[:1]) + p[1:]
		}
	}
	return strings.Join(parts, "")
}

// writeSchemaIndex maps resource and data source names to the generated
// schema functions, since Go cannot discover the generated packages at runtime.
func writeSchemaIndex(path string, merged map[string]any) error {
	var b bytes.Buffer
	module := "github.com/appgate/terraform-provider-appgatesdp/" + FrameworkDir
	fmt.Fprintf(&b, "// %s\n\npackage provider\n\nimport (\n\"context\"\n\n", generatedHeader)
	fmt.Fprintf(&b, "dschema \"github.com/hashicorp/terraform-plugin-framework/datasource/schema\"\n")
	fmt.Fprintf(&b, "rschema \"github.com/hashicorp/terraform-plugin-framework/resource/schema\"\n\n")
	names := func(kind string) []string {
		var out []string
		for _, r := range listOf(merged[kind]) {
			out = append(out, r.(map[string]any)["name"].(string))
		}
		slices.Sort(out)
		return out
	}
	resources, dataSources := names("resources"), names("datasources")
	for _, n := range resources {
		fmt.Fprintf(&b, "\"%s/resource_%s\"\n", module, n)
	}
	for _, n := range dataSources {
		fmt.Fprintf(&b, "\"%s/datasource_%s\"\n", module, n)
	}
	b.WriteString(")\n\n// generatedResourceSchemas lists the superset schema of every generated resource.\n")
	b.WriteString("var generatedResourceSchemas = map[string]func(context.Context) rschema.Schema{\n")
	for _, n := range resources {
		fmt.Fprintf(&b, "%q: resource_%s.%sResourceSchema,\n", n, n, pascal(n))
	}
	b.WriteString("}\n\n// generatedDataSourceSchemas lists the superset schema of every generated data source.\n")
	b.WriteString("var generatedDataSourceSchemas = map[string]func(context.Context) dschema.Schema{\n")
	for _, n := range dataSources {
		fmt.Fprintf(&b, "%q: datasource_%s.%sDataSourceSchema,\n", n, n, pascal(n))
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("format %s: %w", path, err)
	}
	return writeFile(path, src)
}

// writeReport documents the provenance and lossy normalizations of a version.
func writeReport(path string, v apiversion.Version, res *buildResult) error {
	var b bytes.Buffer
	fmt.Fprintf(&b, "<!-- %s -->\n# API %s generation report\n\n", generatedHeader, v.APIVersion)
	fmt.Fprintf(&b, "| | |\n|---|---|\n| SDP version | %s |\n| Branch | `%s` |\n| Commit | `%s` |\n\n", v.SDPVersion, v.Branch, v.Commit)
	fmt.Fprintf(&b, "Resources: %d, data sources: %d.\n\n", len(res.api.Resources), len(res.api.DataSources))
	b.WriteString("## Resources not available in this version\n\n")
	if len(res.unsupported) == 0 {
		b.WriteString("None.\n")
	}
	for _, name := range sortedKeys(res.unsupported) {
		fmt.Fprintf(&b, "- `%s`: %s\n", name, res.unsupported[name])
	}
	b.WriteString("\n## Path classification\n\nEvery path of the specification and how the provider exposes it.\n\n| Path | Exposed as | Detail |\n|---|---|---|\n")
	for _, p := range sortedKeys(res.classes) {
		c := res.classes[p]
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", p, c.Kind, c.Detail)
	}
	b.WriteString("\n## Normalization warnings\n\nSchema constructs the generator cannot express and that were dropped or simplified.\n\n")
	if len(res.warnings) == 0 {
		b.WriteString("None.\n")
	}
	warnings := slices.Clone(res.warnings)
	slices.Sort(warnings)
	for _, w := range slices.Compact(warnings) {
		fmt.Fprintf(&b, "- %s\n", w)
	}
	return writeFile(path, b.Bytes())
}

// writeVersionsDoc renders the support matrix of resources and attributes.
func writeVersionsDoc(path string, reg apiversion.Registry, apis map[string]*apimeta.API, merged map[string]any) error {
	var b bytes.Buffer
	names := reg.Names()
	fmt.Fprintf(&b, "---\npage_title: \"Supported SDP API versions\"\n---\n\n<!-- %s -->\n\n# Supported SDP API versions\n\n", generatedHeader)
	b.WriteString("| API version | SDP version | Specification branch | Pinned commit |\n|---|---|---|---|\n")
	for _, v := range reg.Versions {
		fmt.Fprintf(&b, "| %s | %s | `%s` | [`%s`](%s/tree/%s) |\n", v.APIVersion, v.SDPVersion, v.Branch, v.Commit[:12], strings.TrimSuffix(reg.Repository, ".git"), v.Commit)
	}
	for _, kind := range []string{"resources", "datasources"} {
		title, prefix := "Resources", "appgatesdp_"
		if kind == "datasources" {
			title = "Data sources"
		}
		fmt.Fprintf(&b, "\n## %s\n\n| Name | %s |\n|---|%s\n", title, strings.Join(names, " | "), strings.Repeat("---|", len(names)))
		var differences bytes.Buffer
		for _, r := range listOf(merged[kind]) {
			name := r.(map[string]any)["name"].(string)
			row := []string{"`" + prefix + name + "`"}
			support := map[string][]string{}
			var present []string
			for _, v := range names {
				m := apis[v].Resources
				if kind == "datasources" {
					m = apis[v].DataSources
				}
				res, ok := m[name]
				if !ok {
					row = append(row, "—")
					continue
				}
				row = append(row, "✓")
				present = append(present, v)
				collectFieldPaths("", res.Fields, v, support)
			}
			fmt.Fprintf(&b, "| %s |\n", strings.Join(row, " | "))
			if kind != "resources" {
				continue
			}
			var lines []string
			for _, p := range sortedKeys(support) {
				if len(support[p]) != len(present) {
					lines = append(lines, fmt.Sprintf("  - `%s`: %s", p, strings.Join(support[p], ", ")))
				}
			}
			if len(lines) > 0 {
				fmt.Fprintf(&differences, "- `%s%s`\n%s\n", prefix, name, strings.Join(lines, "\n"))
			}
		}
		if differences.Len() > 0 {
			b.WriteString("\n### Attributes that differ between API versions\n\nAttributes listed with the API versions that support them. Setting an attribute the configured `api_version` does not support is a plan-time error.\n\n")
			b.Write(differences.Bytes())
		}
	}
	return writeFile(path, b.Bytes())
}

func collectFieldPaths(prefix string, fields map[string]*apimeta.Field, version string, out map[string][]string) {
	for name, f := range fields {
		p := prefix + name
		out[p] = append(out[p], version)
		collectFieldPaths(p+".", f.Fields, version, out)
	}
}

func writeFile(path string, b []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, b, 0o644)
}
